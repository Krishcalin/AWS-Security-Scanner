#!/usr/bin/env python3
"""Render docs/CIS_AL2_BENCHMARK.md from engine/aws_cis_al2_map.py.

    python scripts/cis_al2_benchmark.py

GENERATED. Do not hand-edit the output. The mapping lives in `engine/aws_cis_al2_map.py`
as data so this document cannot drift from the catalogue it describes, and
`tests/test_cis_al2.py` fails the build when it has.

This document says something the other three benchmark documents do not have to: that
most of what it covers cannot be seen. Publishing that plainly is the point — a coverage
document that reports only its wins is marketing, and this one would be 12% marketing.
"""
from __future__ import annotations

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from engine import aws_cis_al2 as A                                # noqa: E402
from engine import aws_cis_al2_map as M                            # noqa: E402
from engine.aws_live_scanner import CHECK_SEVERITY as S            # noqa: E402

SOURCE_LABEL = {
    M.FILE:     "file content",
    M.FILEMODE: "file permissions",
    M.ACCOUNT:  "account files",
    M.KERNEL:   "running kernel",
    M.PKG:      "installed packages",
    M.SERVICE:  "systemd units",
    M.OTHER:    "unclassified",
}

PREAMBLE = """# CIS Amazon Linux 2 Benchmark v4.0.0 — coverage

**All 287 recommendations, what kind of state each one's audit reads, and whether
OverWatch can see it.**

> **On the source document.** CIS Benchmarks may not be redistributed, and the PDF is
> deliberately not in this repository. This document cites recommendation *numbers*,
> which are references, and classifies each one's audit — analysis that is this project's
> own. Unlike the sibling benchmark documents it reproduces **no recommendation titles at
> all**, not even paraphrased.

**GENERATED by `scripts/cis_al2_benchmark.py` from `engine/aws_cis_al2_map.py`. Do not
hand-edit.**

## The headline, which is not a comfortable one

This is an **operating system** benchmark and OverWatch is an **agentless control-plane
scanner**. Those two facts decide almost everything below: 252 of the 287 recommendations
read state that lives inside the instance — the contents of `/etc/ssh/sshd_config`, PAM
stacks, sysctl values, file modes — and the control plane does not carry any of it.

So this document reports **35 of 287 decided**, and spends the rest of its length being
specific about why the others are not. Each blocked recommendation names the *capability*
it is waiting on rather than being filed as a backlog item, because "not built yet" and
"cannot be seen at all" are different claims and only one of them is actionable this
quarter.

## Why no checks were registered for the other 252

Registering them would have put the largest block of registered-but-unreachable checks in
this product's history into the catalogue. That is the precise failure
`docs/CHECK_FIRING.md` measures and `tests/test_unreached_modules.py` keeps at zero: a
check that is registered, counted in the published total, and cannot fire reads to every
consumer as coverage. When the filesystem extractor lands, this file is the work list —
already sorted by what each row needs.
"""


def build() -> str:
    out = [PREAMBLE]

    by_src = M.by_source()
    out.append("\n## What kind of state the benchmark reads\n")
    out.append("| Source | Recommendations | Reachable today |")
    out.append("|---|---:|---|")
    for src in M.SOURCES:
        n = by_src.get(src, 0)
        if not n:
            continue
        cov = sum(1 for r, v in M.RECOMMENDATIONS.items()
                  if v[0] == src and v[1] == M.COVERED)
        note = f"{cov} of {n}" if cov else "none"
        out.append(f"| {SOURCE_LABEL[src]} | {n} | {note} |")
    total = sum(by_src.values())
    covered = sum(1 for v in M.RECOMMENDATIONS.values() if v[1] == M.COVERED)
    out.append(f"| **total** | **{total}** | **{covered}** |")

    out.append("\n## What each blocked recommendation is waiting on\n")
    for name, why in sorted(M.BLOCKERS.items()):
        n = sum(1 for v in M.RECOMMENDATIONS.values() if v[3] == name)
        out.append(f"### `{name}` — {n} recommendation(s)\n")
        out.append(why + "\n")

    out.append("\n## The checks that do fire\n")
    out.append("| Check | Severity | Decides | What it reads |")
    out.append("|---|---|---:|---|")
    for c in A.CHECKS:
        n = sum(1 for v in M.RECOMMENDATIONS.values()
                if v[1] == M.COVERED and c.id in v[2])
        reads = ("SSM Inventory AWS:Application" if c.id != "AL2-03"
                 else "SSM Inventory AWS:Service")
        out.append(f"| **{c.id}** | {S[c.id]} | {n} | {reads} |")
    out.append("\n`AL2-00` is an INFO-only coverage statement and is deliberately not "
               "registered: it says what a host could *not* be assessed for, and an "
               "empty finding list is otherwise indistinguishable from a clean host.\n")

    out.append("\n## By subsection\n")
    out.append("| # | What it covers | Recs | Decided |")
    out.append("|---|---|---:|---:|")
    for num, label, count, cov in M.SUBSECTIONS:
        mark = f"**{cov}**" if cov else "—"
        out.append(f"| {num} | {label} | {count} | {mark} |")

    out.append("\n## Every recommendation\n")
    out.append("| # | Reads | Verdict | Check(s) / blocker |")
    out.append("|---|---|---|---|")
    for rec in sorted(M.RECOMMENDATIONS, key=M._sort_key):
        src, verdict, checks, blocker = M.RECOMMENDATIONS[rec]
        if verdict == M.COVERED:
            right = ", ".join(f"**{c}**" for c in checks)
            v = "decided"
        else:
            right = f"`{blocker}`"
            v = "blocked"
        out.append(f"| {rec} | {SOURCE_LABEL[src]} | {v} | {right} |")

    out.append("\n## The packages and units this reads for\n")
    out.append("Package and unit NAMES are facts about the operating system rather than "
               "the benchmark's prose, which is why they appear here verbatim when its "
               "titles do not.\n")
    out.append(f"**Prohibited packages ({len(A.PROHIBITED_PACKAGES)}):** "
               + ", ".join(f"`{p}`" for p in sorted(A.PROHIBITED_PACKAGES)) + "\n")
    out.append(f"**Required packages ({len(A.REQUIRED_PACKAGES)}):** "
               + ", ".join(f"`{p}`" for p in sorted(A.REQUIRED_PACKAGES)) + "\n")
    out.append(f"**Prohibited units ({len(A.PROHIBITED_UNITS)}):** "
               + ", ".join(f"`{u}`" for u in sorted(A.PROHIBITED_UNITS)) + "\n")
    return "\n".join(out)


def main() -> int:
    path = os.path.join(ROOT, "docs", "CIS_AL2_BENCHMARK.md")
    io.open(path, "w", encoding="utf-8", newline="\n").write(build())
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
