def RENUMBER_TABLE() -> str:
    rows = ["\n## The renumbering, in full\n",
            "Every recommendation OverWatch cited under v3.0, and where it went. A reader "
            "holding an older report can reconcile it with this.\n",
            "| v3.0 | v7.0.0 | Control |", "|---|---|---|"]
    for old in sorted(M.RENUMBERED, key=M._sort_key):
        new = M.RENUMBERED[old]
        label = M.RECOMMENDATIONS[new][0]
        rows.append(f"| {old} | **{new}** | {label} |")
    return "\n".join(rows)


def REPOINTED_TABLE() -> str:
    rows = ["\n## Citations the renumbering table gets wrong\n",
            "Nine checks kept a Foundations citation and moved somewhere the table above "
            "would not predict. Six land on **2.21**, which is new in v7.0.0 and had no "
            "predecessor to be renumbered from; the other three were mis-cited under "
            "v3.0 and are corrected on the way.\n",
            "| Check | v3.0 | v7.0.0 | Why the plain renumber is not the answer |",
            "|---|---|---|---|"]
    for cid in sorted(M.REPOINTED):
        old, new, why = M.REPOINTED[cid]
        rows.append(f"| {cid} | {old} | **{new}** | {why} |")
    return "\n".join(rows)


def MISCITED_TABLE() -> str:
    rows = ["\n## Citations removed, and why\n",
            "A citation that points at the wrong control is worse than none: it sends an "
            "auditor to a recommendation about something else, and the number looks "
            "right on the way. Each of these keeps its PCI-DSS, HIPAA, SOC 2 and NIST "
            "mappings — only the Foundations claim goes.\n",
            "| Check | Carried | Why it was wrong |", "|---|---|---|"]
    for cid in sorted(M.MISCITED):
        old, why = M.MISCITED[cid]
        rows.append(f"| {cid} | {old} | {why} |")
    rows.append("\n### Kubernetes numbering under the Foundations key\n")
    rows.append("Coherent against the CIS EKS benchmark, impossible against this one. "
                "Kept as data in `EKS_NUMBERED`; building a verified `CIS-EKS` mapping "
                "is recorded as follow-on work.\n")
    rows.append("| Check | Carried |")
    rows.append("|---|---|")
    for cid in sorted(M.EKS_NUMBERED):
        rows.append(f"| {cid} | {M.EKS_NUMBERED[cid]} |")
    return "\n".join(rows)


def main() -> int:
    path = os.path.join(ROOT, "docs", "CIS_FOUNDATIONS_BENCHMARK.md")
    io.open(path, "w", encoding="utf-8", newline="\n").write(build())
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
