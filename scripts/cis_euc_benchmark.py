#!/usr/bin/env python3
"""Render docs/CIS_EUC_BENCHMARK.md from engine/aws_cis_euc_map.py.

    python scripts/cis_euc_benchmark.py            # write
    python scripts/cis_euc_benchmark.py --check    # CI: fail if stale

The mapping is the data and this is the renderer, for the reason the four sibling
benchmark documents are generated: a 34-row table typed into markdown sits next to a
catalogue that moves, and stops being true the first time a check is renamed.
tests/test_cis_euc_mapping.py asserts both directions.

NO TIMESTAMP IS EMITTED. A generator that reads the clock cannot be checked against
its own output -- see the comment in scripts/gen_ccm_matrix.py, which learned it the
expensive way.

NOTHING FROM THE SOURCE DOCUMENT IS REPRODUCED. Recommendation NUMBERS are
references; the labels and notes are this project's own analysis, written from what
the AWS APIs expose. CIS Benchmarks may not be redistributed.
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from engine import aws_cis_euc_map as M          # noqa: E402

OUT = os.path.join(ROOT, "docs", "CIS_EUC_BENCHMARK.md")

VERDICT_LABEL = {
    M.COVERED: "covered",
    M.ELSEWHERE: "decided elsewhere",
    M.NO_CHECK: "gap",
    M.BLOCKED: "blocked",
    M.UNSOUND: "UNSOUND",
}
ORDER = (M.COVERED, M.ELSEWHERE, M.NO_CHECK, M.BLOCKED, M.UNSOUND)

MEANINGS = {
    M.COVERED: "A named check decides it and can FAIL on it.",
    M.ELSEWHERE: "Decided, but by a check outside this benchmark's own services "
                 "— the IAM or segmentation pillars, which fail the condition "
                 "generically.",
    M.NO_CHECK: "Decidable from the AWS control plane, not currently checked. "
                "The real backlog.",
    M.BLOCKED: "No read-only control-plane path exists, or the only path reads "
               "workload DATA and is refused. See the blockers below.",
    M.UNSOUND: "**The recommendation's own audit does not test the thing it "
               "recommends.** Implementing it faithfully would produce a check "
               "that passes and fails for reasons unrelated to the control.",
}


def _rows_in(section: str):
    return sorted(
        ((r, v) for r, v in M.RECOMMENDATIONS.items()
         if r.split(".", 1)[0] == section),
        key=lambda kv: int(kv[0].split(".", 1)[1]),
    )


def render() -> str:
    total = len(M.RECOMMENDATIONS)
    counts = {v: len(M.by_verdict(v)) for v in M.VERDICTS}
    out: list[str] = []
    w = out.append

    w("# CIS AWS End User Compute Services Benchmark v1.2.0 — coverage")
    w("")
    w(f"**All {total} recommendations, and what OverWatch does about each one.**")
    w("")
    w("> **On the source document.** CIS Benchmarks may not be redistributed, and "
      "the PDF is deliberately not in this repository. This document cites "
      "recommendation *numbers*, which are references, and pairs each with a label "
      "and a verdict that are this project's own analysis. No recommendation title, "
      "rationale, audit or remediation text is reproduced.")
    w("")
    w("**GENERATED by `scripts/cis_euc_benchmark.py` from "
      "`engine/aws_cis_euc_map.py`. Do not hand-edit.**")
    w("")

    w("## What this benchmark is about")
    w("")
    w("Managed desktops and streamed applications: WorkSpaces, WorkSpaces Web, "
      "WorkDocs and AppStream 2.0. That is an employee's whole working environment "
      "— the machine they read mail on, the browser they are phished in, the "
      "documents they keep — running in your account and reachable from any device "
      "on the internet unless somebody narrowed that. Before this mapping, "
      "OverWatch could see exactly one of the four (WorkSpaces Web, two checks).")
    w("")
    w("It is a **better document than its Storage sibling**. 13 of its 34 "
      "recommendations are Automated where Storage had none, and most of section 5 "
      "maps onto fields the API returns plainly.")
    w("")

    w("## Two findings that came from the API, not the text")
    w("")
    workdocs_blocked = [r for r in M.by_verdict(M.BLOCKED)
                        if r.startswith("4.")]
    w(f"**{len(workdocs_blocked)} of the 8 WorkDocs recommendations are "
      "unreachable, and that is a refusal rather than a backlog item.** The other "
      "two are generic IAM and directory-MFA hygiene, decided elsewhere. Every "
      "operation in the "
      "`workdocs` service model is document- or user-scoped and takes an "
      "`AuthenticationToken`, which is issued to a signed-in WorkDocs *user*, not "
      "to an IAM role. There is no administrative API returning the site settings "
      "4.3 through 4.8 govern. The operations a token *would* unlock — "
      "`DescribeUsers`, `GetDocument`, `SearchResources` — read customer documents, "
      "which this product refuses by charter. These rows stay blocked even if a "
      "token were available.")
    w("")
    w("**2.17 cannot be audited from the account being scanned.** It asks that "
      "WorkSpaces API calls travel over a VPC endpoint. Whether a call traversed an "
      "endpoint is a property of the *caller's* network path; the account records "
      "nothing about it. The stated audit asks the operator to pass "
      "`--endpoint-url` themselves and confirm the value they passed came back — "
      "which would pass from any network, including the open internet. Its "
      "remediation compounds the error by creating an endpoint for "
      "`elasticloadbalancing`, a different service entirely.")
    w("")

    w("## Verdicts")
    w("")
    w("| Verdict | Count | Meaning |")
    w("|---|---:|---|")
    for v in ORDER:
        w(f"| `{VERDICT_LABEL[v]}` | {counts[v]} | {MEANINGS[v]} |")
    w(f"| **total** | **{total}** | |")
    w("")

    w("## What is blocked, and on what")
    w("")
    for name, why in sorted(M.BLOCKERS.items()):
        # `in`, not `endswith`: a blocked row may carry further prose after naming
        # its blocker, and 4.7 does. endswith silently dropped it from the count.
        rows = [r for r in M.by_verdict(M.BLOCKED)
                if f"Blocker: {name}." in M.RECOMMENDATIONS[r][3]]
        w(f"**{name}** ({len(rows)} recommendation(s): {', '.join(rows)}) — {why}")
        w("")

    for num, name, _declared in M.SECTIONS:
        rows = _rows_in(num)
        w(f"## {num} {name}")
        w("")
        w(f"{len(rows)} recommendations.")
        w("")
        w("| # | What it reaches for | Verdict | Checks | Note |")
        w("|---|---|---|---|---|")
        for rec, (label, verdict, checks, note) in rows:
            ck = ", ".join(f"`{c}`" for c in checks) if checks else "—"
            w(f"| {rec} | {label} | `{VERDICT_LABEL[verdict]}` | {ck} | {note} |")
        w("")

    w("## Checks carrying the `CIS-EUC` key")
    w("")
    w("The key lands only on a check named by a `covered` row **and** belonging to "
      "that row's own service section, so a benchmark mapping cannot quietly "
      "re-label checks owned by other pillars.")
    w("")
    homes = []
    for rec, (_l, verdict, checks, _n) in M.RECOMMENDATIONS.items():
        if verdict != M.COVERED:
            continue
        for c in checks:
            if M.FAMILY_SECTION.get(c.rsplit("-", 1)[0]) == rec.split(".", 1)[0]:
                homes.append((c, M.recommendation_for(c)))
    w("| Check | Recommendation |")
    w("|---|---|")
    for c, rec in sorted(set(homes)):
        w(f"| `{c}` | {rec} |")
    w("")
    w("`WKS-08` and `APS-05` answer no recommendation here and carry no key. That "
      "is the finding rather than an omission: the benchmark never asks whether "
      "desktop users are local administrators of their own machine, nor whether an "
      "AppStream fleet still answers IMDSv1 — the credential-theft path EC2 closed "
      "with IMDSv2, on instances whose whole purpose is running software a user "
      "chose.")
    w("")

    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the document on disk is stale")
    args = ap.parse_args()

    rendered = render()
    if args.check:
        existing = None
        if os.path.isfile(OUT):
            with open(OUT, encoding="utf-8") as fh:
                existing = fh.read()
        if existing != rendered:
            print("STALE: regenerate with scripts/cis_euc_benchmark.py",
                  file=sys.stderr)
            return 1
        print("docs/CIS_EUC_BENCHMARK.md is up to date")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)
    print(f"wrote {os.path.relpath(OUT, ROOT)} "
          f"({len(M.RECOMMENDATIONS)} recommendations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
