VERDICT_LABEL = {
    M.COVERED:   "covered",
    M.PARTIAL:   "observed only",
    M.ELSEWHERE: "decided elsewhere",
    M.NO_CHECK:  "**gap**",
    M.DECLINED:  "declined",
    M.PROCESS:   "process",
    M.VACUOUS:   "vacuous",
}

PREAMBLE = """# CIS AWS Database Services Benchmark v2.0.0 — coverage

**All 98 recommendations across ten services, and what OverWatch does about each.**
Nothing is listed as covered without naming the check that covers it, and a check that
cannot FAIL is never counted as covering anything — it can tell you a setting's value, but
it can never tell an operator they are non-compliant.

> **On the source document.** CIS Benchmarks may not be redistributed, and the PDF is
> deliberately not in this repository. What is cited below is the recommendation *number*,
> which is a reference, together with a one-line label written from the underlying AWS
> behaviour. No rationale, audit, impact or remediation text is reproduced.

**GENERATED by `scripts/cis_db_benchmark.py` from `engine/aws_cis_db_map.py`. Do not
hand-edit.**

## How to read the verdicts

| Verdict | Meaning |
|---|---|
| covered | A named check decides it and can FAIL on it. |
| observed only | A check reads the setting and reports it, but never FAILs. Real coverage of the observation, not of the finding. |
| decided elsewhere | Answered outside these services — by the segmentation, CloudTrail or CIEM pillars — or, in two cases, by the wrong check. See the defects section. |
| **gap** | Decidable from the control plane today, and not checked. This is the honest backlog. |
| declined | Deliberately not built, with the reason recorded in `engine/aws_cis_db.py` rather than left as silence. |
| process | Asks about a human process: a review cadence, a design exercise, a procurement decision. No API read can decide it. |
| vacuous | True of every modern account by construction, so a check would pass universally and measure nothing. |

## Why `CIS-DB` and not `CIS`

123 checks already carry a `CIS` key and every one of them is CIS AWS **Foundations**
numbering. The service benchmarks reuse those section numbers for entirely unrelated
controls — Foundations 2.2 is CloudTrail log-file validation, Compute 2.2 is EBS
encryption, Database 2.2 is Aurora encryption at rest. Folding them into one key would
mis-cite every mapping in both directions at once, so Database controls carry their own
`CIS-DB` key, exactly as Compute controls carry `CIS-COMPUTE`.
"""

DEFECTS = """
## Defects found in the benchmark itself

Mapping a document line by line is an unusually thorough read of it. These are errors in
the published benchmark, recorded because each one changes what a conscientious auditor
should do with the recommendation — not as criticism for its own sake.

**5.8, 5.9 and 5.10 are filed under ElastiCache but audit Amazon Keyspaces.** All three
sit in section 5, and all three instruct the reader to open the Amazon Keyspaces console
and select a keyspace. ElastiCache has no keyspaces. Read literally the three controls are
unperformable; read charitably, 5.8 duplicates 5.1 and 5.9 has no ElastiCache meaning at
all. This also explains the duplicate title in the next item.

**5.7 and 5.10 carry the same title.** Both are "Ensure Security Configurations are
Reviewed Regularly". 5.7 is the genuine ElastiCache one; 5.10 is part of the misfiled
Keyspaces block. An estate tracking compliance by title will silently collapse them.

**3.13 and 3.14 audit RDS with a cluster-only API.** Both tell the reader to run
`aws rds describe-db-clusters`. Most RDS estates are standalone instances, for which that
call returns an empty list — which reads as "no findings" rather than "wrong question".
`IAMDatabaseAuthenticationEnabled` and `DeletionProtection` are instance-level fields, and
RDS-08 and RDS-04 read them there.

**7.3 asks for something DocumentDB cannot do.** Its remediation walks the reader through
modifying encryption at rest on an existing cluster. DocumentDB fixes encryption at
creation; there is no modify path. The only real remediation is a snapshot-and-restore
into a new encrypted cluster, which is a materially different piece of work to plan.

**5.13 is unsatisfiable on Memcached.** The audit treats `SnapshotRetentionLimit = 0` as
non-compliant across all ElastiCache clusters, but Memcached does not support snapshots at
all, so every Memcached cluster fails permanently with no available fix. ELC-07 scopes
itself to replication groups, which is where the setting means something.

**10.10 carries leftover text from another control.** Its remediation defines a single
on-demand backup rule, then instructs the reader to "replace 35 with your retention time
for PITR" — a value and a concept that appear nowhere else in the control. The same
paragraph in 4.9, which does have a PITR rule, is where it belongs.

**2.8's audit contradicts its own service.** It tells the reader that setting the
retention period to 0 disables automatic backups. For an Aurora *cluster* the minimum is 1
and 0 cannot be set, so the state the control warns about is unreachable. AUR-07 therefore
fails below 7 days rather than at 0 — a check written to the literal text would never fire.

**Several recommendations ship with empty fields.** 3.1 and 3.2 have no Description and no
Rationale; 2.4, 2.5, 3.5–3.11 and others have an empty Remediation. 3.1 in particular
("choose the appropriate database engine") is a procurement exercise with no state to
audit, which its empty fields make plain.
"""

FINDINGS = """
## What the mapping found in OverWatch

**The RDS instance loop scores Neptune and DocumentDB instances as RDS.** This is the same
defect that tranche 1 fixed for *clusters*, still present one level down. Neptune and
DocumentDB share the RDS control plane, so `rds:DescribeDBInstances` returns their
instances, and `_rds_instances()` applies no engine filter. Run against a single Neptune
instance the section produces four findings — RDS-01, RDS-02, RDS-03 and RDS-04 — none of
which say Neptune anywhere.

Two consequences, and they pull in opposite directions:

* RDS-01 and RDS-04 **double-report**. Cluster storage encryption is already reported as
  NEP-01 or DOCDB-02, and deletion protection as NEP-02 or DOCDB-04, so the same fact
  arrives twice under two ids with two different remediation commands.
* RDS-02 and RDS-03 are the **only** coverage of Neptune 9.8 and 9.9. Nothing else reads
  public accessibility or backup retention for Neptune. Deleting the RDS finding without
  adding a Neptune one would remove real coverage, which is exactly the trap tranche 1
  avoided by expanding from zero new checks to six.

That is why 9.8 and 9.9 are recorded above as *decided elsewhere* rather than as covered
or as gaps: neither would be true. Fixing it properly means filtering the instance loop
and adding the Neptune and DocumentDB instance-level checks in the same change.

**The gaps are concentrated and unglamorous.** Of the 17, the ones that would close real
exposure are DocumentDB backup retention (7.9), Neptune IAM authentication (9.4), Neptune
audit logging (9.5) and Neptune Multi-AZ (9.11) — every one of which already exists for a
sibling service, so each is a small variation on a check that ships today rather than new
ground.
"""


def _stat(rec):
    return M.RECOMMENDATIONS[rec][1]


def build() -> str:
    out = [PREAMBLE]
    tally = {v: 0 for v in M.VERDICTS}

    for num, name, count in M.SECTIONS:
        recs = [r for r in M.RECOMMENDATIONS if r.split(".", 1)[0] == num]
        recs.sort(key=lambda r: int(r.split(".")[1]))
        got = sum(1 for r in recs if _stat(r) == M.COVERED)
        out.append(f"\n## {num} — {name}")
        out.append(f"\n*{len(recs)} recommendations; {got} covered by a check that can "
                   f"fail.*\n")
        out.append("| # | Control | Verdict | OverWatch | Note |")
        out.append("|---|---|---|---|---|")
        for r in recs:
            label, verdict, checks, note = M.RECOMMENDATIONS[r]
            tally[verdict] += 1
            shown = ", ".join(f"**{c}**" for c in checks) if checks else "—"
            out.append(f"| {r} | {label} | {VERDICT_LABEL[verdict]} | {shown} | "
                       f"{note or ''} |")
        out.append("")

    total = sum(tally.values())
    out.append("\n## Totals\n")
    out.append("| Verdict | Recommendations |")
    out.append("|---|---:|")
    for v in M.VERDICTS:
        out.append(f"| {VERDICT_LABEL[v]} | {tally[v]} |")
    out.append(f"| **total** | **{total}** |")

    keyed = sorted(c for c, v in C.items() if "CIS-DB" in v)
    fams = set(M.FAMILY_SECTION)
    owned = sorted(c for c in S if c.rsplit("-", 1)[0] in fams)
    orphan = [c for c in owned if c not in keyed]
    out.append(
        f"\n{len(keyed)} checks carry a `CIS-DB` compliance key. {len(orphan)} more speak "
        f"to these services but answer no recommendation in this benchmark — they are "
        f"coverage the document does not ask for:\n")
    for c in orphan:
        rec_note = {
            "AUR-03": "Aurora engine end-of-life — section 2 has no patching control",
            "AUR-04": "publicly restorable Aurora snapshot — no snapshot-sharing control",
            "DDB-03": "DynamoDB auto scaling — a throttling risk the benchmark omits",
            "DOCDB-01": "publicly restorable DocumentDB snapshot — no such control",
            "MDB-05": "MemoryDB minor-version patching — section 6 has no patching control",
            "MDB-06": "MemoryDB single-AZ — section 6 has no availability control",
            "NEP-03": "publicly restorable Neptune snapshot — no such control",
            "RDS-06": "publicly accessible RDS snapshot — no snapshot-sharing control",
            "RDS-13": "idle instance still holding live data — cost and exposure hygiene",
        }.get(c, "")
        out.append(f"- **{c}** ({S[c]}) — {rec_note}")

    out.append(DEFECTS)
    out.append(FINDINGS)

    out.append("\n## Declines, in full\n")
    out.append("Held as data in `engine/aws_cis_db.py` so this document, the coverage "
               "tests and the inventory all read the same list.\n")
    for k, reason in sorted(aws_cis_db.NOT_DETERMINABLE.items()):
        out.append(f"- **`{k}`** — {reason}\n")
    for k, reason in sorted(aws_cis_db.DECLINED_AS_NOT_A_FINDING.items()):
        out.append(f"- **`{k}`** *(readable, judged not a finding)* — {reason}\n")
    return "\n".join(out)


def main() -> int:
    path = os.path.join(ROOT, "docs", "CIS_DATABASE_BENCHMARK.md")
    io.open(path, "w", encoding="utf-8", newline="\n").write(build())
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
