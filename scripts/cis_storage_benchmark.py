#!/usr/bin/env python3
"""Render docs/CIS_STORAGE_BENCHMARK.md from engine/aws_cis_storage_map.py.

    python scripts/cis_storage_benchmark.py            # write
    python scripts/cis_storage_benchmark.py --check    # CI: fail if stale

The mapping is the data and this is the renderer, for the same reason the three
sibling benchmark documents are generated: a 56-row table typed into markdown sits
next to a catalogue that moves and stops being true the first time a check is
renamed. tests/test_cis_storage_mapping.py asserts both directions.

NOTHING FROM THE SOURCE DOCUMENT IS REPRODUCED. Recommendation NUMBERS are
references; the labels and notes are this project's own analysis, written from what
the AWS APIs expose. CIS Benchmarks may not be redistributed.
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from engine import aws_cis_storage_map as M          # noqa: E402

OUT = os.path.join(ROOT, "docs", "CIS_STORAGE_BENCHMARK.md")

#: How each verdict is presented, and in what order the summary lists them.
VERDICT_LABEL = {
    M.COVERED: "covered",
    M.ELSEWHERE: "decided elsewhere",
    M.NO_CHECK: "gap",
    M.BLOCKED: "blocked",
    M.PROCESS: "process",
    M.VACUOUS: "vacuous",
    M.NO_AUDIT: "no audit procedure",
    M.DECLINED: "declined",
    M.UNSAFE: "UNSAFE",
}
ORDER = (M.COVERED, M.ELSEWHERE, M.NO_CHECK, M.BLOCKED, M.PROCESS, M.VACUOUS,
         M.NO_AUDIT, M.DECLINED, M.UNSAFE)


def _rows_in(section: str):
    return sorted(
        ((r, v) for r, v in M.RECOMMENDATIONS.items()
         if r.split(".", 1)[0] == section),
        key=lambda kv: int(kv[0].split(".", 1)[1]),
    )


def render() -> str:
    total = len(M.RECOMMENDATIONS)
    counts = {v: len(M.by_verdict(v)) for v in M.VERDICTS}
    out: list[str] = []
    w = out.append

    w("# CIS AWS Storage Services Benchmark v1.0.0 — coverage")
    w("")
    w(f"**All {total} recommendations, and what OverWatch does about each one.**")
    w("")
    w("> **On the source document.** CIS Benchmarks may not be redistributed, and "
      "the PDF is deliberately not in this repository. This document cites "
      "recommendation *numbers*, which are references, and pairs each with a label "
      "and a verdict that are this project's own analysis. No recommendation title, "
      "rationale, audit or remediation text is reproduced.")
    w("")
    w("**GENERATED by `scripts/cis_storage_benchmark.py` from "
      "`engine/aws_cis_storage_map.py`. Do not hand-edit.**")
    w("")

    w("## The headline, which is not a comfortable one")
    w("")
    w(f"CIS marks **all {total} of these recommendations \"Manual\"**. Not one is "
      "Automated. The benchmark's own definitions reserve that word for controls "
      "whose assessment \"can be fully automated and validated to a pass/fail "
      "state\", so the authors are saying up front that none of this reduces to the "
      "kind of read a scanner makes. The Foundations, Compute and Database "
      "benchmarks all carry substantial Automated sets; this one carries none.")
    w("")
    w(f"Two further facts shape every row below. **{counts[M.NO_AUDIT]} "
      "recommendations have no audit procedure at all** — the heading is present "
      "and the body is empty — which is neither a gap nor a decline but a hole in "
      f"the source. And **{counts[M.UNSAFE]} would reduce security if followed**, "
      "which is why this mapping carries an `UNSAFE` verdict that none of its "
      "siblings needs.")
    w("")

    w("## Verdicts")
    w("")
    w("| Verdict | Count | Meaning |")
    w("|---|---:|---|")
    meanings = {
        M.COVERED: "A named check decides it and can FAIL on it.",
        M.ELSEWHERE: "Decided, but by a check outside this benchmark's storage "
                     "services — the IAM, segmentation or logging pillars.",
        M.NO_CHECK: "Decidable from the AWS control plane, not currently checked. "
                    "The real backlog.",
        M.BLOCKED: "Needs state inside an instance. No read-only control-plane path "
                   "to it exists — see the blocker below.",
        M.PROCESS: "Asks about a human process: a drill, a review cadence, a "
                   "documented plan.",
        M.VACUOUS: "True by construction, or not a security property at all.",
        M.NO_AUDIT: "The source recommendation's Audit section is **empty**. There "
                    "is no stated test to build.",
        M.DECLINED: "Deliberately not built, with the reason recorded in the row.",
        M.UNSAFE: "**Following the source's own guidance would reduce security.** "
                  "Never to be built.",
    }
    for v in ORDER:
        w(f"| `{VERDICT_LABEL[v]}` | {counts[v]} | {meanings[v]} |")
    w(f"| **total** | **{total}** | |")
    w("")

    w("## What is blocked, and on what")
    w("")
    for name, why in sorted(M.BLOCKERS.items()):
        rows = [r for r in M.by_verdict(M.BLOCKED)]
        w(f"**{name}** ({len(rows)} recommendations: "
          f"{', '.join(rows)}) — {why}")
        w("")

    for num, name, declared in M.SECTIONS:
        rows = _rows_in(num)
        w(f"## {num} {name}")
        w("")
        w(f"{len(rows)} recommendations.")
        w("")
        w("| # | What it reaches for | Verdict | Checks | Note |")
        w("|---|---|---|---|---|")
        for rec, (label, verdict, checks, note) in rows:
            ck = ", ".join(f"`{c}`" for c in checks) if checks else "—"
            w(f"| {rec} | {label} | `{VERDICT_LABEL[verdict]}` | {ck} | {note} |")
        w("")

    w("## Checks carrying the `CIS-STORAGE` key")
    w("")
    w("The key lands only on a check named by a `covered` row **and** belonging to "
      "that row's own service section. `EC2-17` is named by 2.4 and deliberately "
      "does not take the key: it is a Compute-family check and keeps its "
      "`CIS-COMPUTE` citation.")
    w("")
    homes = []
    for rec, (_l, verdict, checks, _n) in M.RECOMMENDATIONS.items():
        if verdict != M.COVERED:
            continue
        for c in checks:
            fam = c.rsplit("-", 1)[0]
            if M.FAMILY_SECTION.get(fam) == rec.split(".", 1)[0]:
                homes.append((c, rec))
    w("| Check | Recommendation |")
    w("|---|---|")
    for c, rec in sorted(homes):
        w(f"| `{c}` | {rec} |")
    w("")
    w("`BCK-04` and `BCK-05` answer no recommendation here and carry no key. That "
      "is the finding rather than an omission: the benchmark's AWS Backup section "
      "asks repeatedly that backups be created and never once asks whether they "
      "survive the loss of the region or the compromise of the account.")
    w("")

    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the document on disk is stale")
    args = ap.parse_args()

    rendered = render()
    if args.check:
        existing = None
        if os.path.isfile(OUT):
            with open(OUT, encoding="utf-8") as fh:
                existing = fh.read()
        if existing != rendered:
            print("STALE: regenerate with scripts/cis_storage_benchmark.py",
                  file=sys.stderr)
            return 1
        print("docs/CIS_STORAGE_BENCHMARK.md is up to date")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)
    print(f"wrote {os.path.relpath(OUT, ROOT)} "
          f"({len(M.RECOMMENDATIONS)} recommendations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
